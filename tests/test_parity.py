"""The Python port must match the original driveindex.com bundle functions exactly.

fixtures_js_parity.json was generated by executing the original (prettified) bundle functions
under Node on 400 seeded-random input sets. See scripts/README.md.
"""

import json
import math
from pathlib import Path

import pytest

from driveindex_model.client_math import (analyze_listing, collectibility, data_strength,
                                          dealer_premium, mileage_adjust, project)

FX = json.loads((Path(__file__).parent / "fixtures_js_parity.json").read_text())


@pytest.mark.parametrize("case", FX["collect"])
def test_collectibility(case):
    mk, md, yr, val, msrp, now = case["args"]
    got = collectibility(mk, md, yr, val, msrp, now)
    assert got.score == case["res"]["score"]
    assert got.reasons == case["res"]["reasons"]


@pytest.mark.parametrize("case", FX["project"])
def test_projection(case):
    val, ann, conf, n, sig, yr, mk, md, msrp, rec, now = case["args"]
    got = project(val, ann, conf, n, sig, yr, mk, md, msrp, rec, now)
    exp = case["res"]
    assert got.forecast1y == exp["forecast1y"]
    assert got.forecast3y == exp["forecast3y"]
    assert got.forecast5y == exp["forecast5y"]
    assert got.bear3y == exp["forecastBear3y"]
    assert got.bull3y == exp["forecastBull3y"]
    assert got.bear5y == exp["forecastBear5y"]
    assert got.bull5y == exp["forecastBull5y"]
    assert got.momentum3y == exp["momentum3y"]
    assert got.momentum5y == exp["momentum5y"]
    assert math.isclose(round(got.rate.blended_rate * 100, 2), exp["methodology"]["blendedRate"],
                        abs_tol=0.011)


@pytest.mark.parametrize("case", FX["strength"])
def test_data_strength(case):
    level, score = data_strength(*case["args"])
    assert level == case["res"]["level"]
    assert math.isclose(score, case["res"]["score"], abs_tol=1e-9)


@pytest.mark.parametrize("case", FX["premium"])
def test_dealer_premium(case):
    assert math.isclose(dealer_premium(*case["args"]), case["res"], rel_tol=1e-12, abs_tol=1e-12)


@pytest.mark.parametrize("case", FX["mileage"])
def test_mileage(case):
    assert mileage_adjust(*case["args"]) == case["res"]


@pytest.mark.parametrize("case", FX["listing"])
def test_listing(case):
    ask, val, miles, avg, cs, age, lb = case["args"]
    got = analyze_listing(ask, val, miles, avg, cs, age, lb)
    assert got.signal == case["res"]["signal"]
    assert got.fair_ask == case["res"]["expected"]
